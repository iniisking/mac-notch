import AppKit
import Combine
import CryptoKit

/// One remembered copy.
struct ClipEntry: Codable, Identifiable, Equatable {
    enum Kind: String, Codable { case text, link, color, image, files }

    var id: UUID = UUID()
    var kind: Kind
    var text: String?
    var files: [String]?
    /// PNG in the history's images folder.
    var imageFile: String?
    var imageSize: CGSize?
    var date: Date
    var app: String?
    var pinned = false
    var hash: String
    var useCount = 0

    var title: String {
        switch kind {
        case .text, .link, .color:
            return NotchNotification.oneLine(text ?? "")
        case .image:
            if let s = imageSize { return "Image (\(Int(s.width))×\(Int(s.height)))" }
            return "Image"
        case .files:
            let names = (files ?? []).map { ($0 as NSString).lastPathComponent }
            return names.count == 1 ? names[0] : "\(names.count) files: \(names.prefix(3).joined(separator: ", "))"
        }
    }
}

/// Clipboard history: polls the pasteboard's change count, stores text, links, colors, images and
/// files, skips anything marked concealed/transient (password managers) and ignored apps. Saved
/// in ~/Library/Application Support/Notch/clipboard.
@MainActor
final class ClipboardHistory: ObservableObject {
    @Published private(set) var entries: [ClipEntry] = []
    /// Fires for local copies (the optional "Copied" moment).
    let copied = PassthroughSubject<ClipEntry, Never>()

    private let settings: LauncherSettings
    private var timer: Timer?
    private var changeCount = NSPasteboard.general.changeCount
    private var saveWork: DispatchWorkItem?
    /// Our own writes (paste-back, copy actions) shouldn't announce a "Copied" moment.
    private var ownWriteUntil = Date.distantPast

    static let dir = LauncherSettings.supportDirectory.appendingPathComponent("clipboard", isDirectory: true)
    static let imagesDir = dir.appendingPathComponent("images", isDirectory: true)
    private static let file = dir.appendingPathComponent("history.json")

    private static let skipTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword", "de.petermaurer.TransientPasteboardType", "com.typeit4me.clipping",
        "Pasteboard generator type", "com.apple.is-remote-clipboard.concealed",
    ]

    init(settings: LauncherSettings) {
        self.settings = settings
        try? FileManager.default.createDirectory(at: Self.imagesDir, withIntermediateDirectories: true)
        entries = JSONFile.load([ClipEntry].self, from: Self.file) ?? []
        prune()
    }

    func start() {
        guard timer == nil else { return }
        changeCount = NSPasteboard.general.changeCount
        let t = Timer(timeInterval: 0.5, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.poll() }
        }
        RunLoop.main.add(t, forMode: .common)
        timer = t
    }

    func stop() {
        timer?.invalidate()
        timer = nil
    }

    /// Called right before Notch itself writes the pasteboard.
    func noteOwnWrite() {
        ownWriteUntil = Date().addingTimeInterval(1.2)
    }

    private func poll() {
        let pb = NSPasteboard.general
        guard pb.changeCount != changeCount else { return }
        changeCount = pb.changeCount
        let types = Set((pb.types ?? []).map(\.rawValue))
        guard types.isDisjoint(with: Self.skipTypes) else { return }
        let app = NSWorkspace.shared.frontmostApplication?.bundleIdentifier
        guard !settings.isIgnored(app) else { return }
        guard var entry = read(pb) else { return }
        entry.app = (app == Bundle.main.bundleIdentifier) ? nil : app
        let isOwn = Date() < ownWriteUntil
        insert(entry)
        if !isOwn, !types.contains("com.apple.is-remote-clipboard") { copied.send(entry) }
    }

    private func read(_ pb: NSPasteboard) -> ClipEntry? {
        // Files first (Finder copies also carry the names as text).
        if let urls = pb.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL], !urls.isEmpty {
            let paths = urls.map(\.path)
            return ClipEntry(kind: .files, files: paths, date: Date(), hash: Self.hash(paths.joined(separator: "\n")))
        }
        if let s = pb.string(forType: .string), !s.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            let trimmed = s.trimmingCharacters(in: .whitespacesAndNewlines)
            var kind = ClipEntry.Kind.text
            if ColorParser.parse(trimmed) != nil { kind = .color }
            else if !trimmed.contains(where: \.isWhitespace), let u = URL(string: trimmed), let scheme = u.scheme,
                    ["http", "https", "mailto", "ftp"].contains(scheme.lowercased()) { kind = .link }
            return ClipEntry(kind: kind, text: s, date: Date(), hash: Self.hash(s))
        }
        if let img = NSImage(pasteboard: pb), let tiff = img.tiffRepresentation,
           let rep = NSBitmapImageRep(data: tiff), let png = rep.representation(using: .png, properties: [:]) {
            let h = Self.hash(png)
            let name = "\(h.prefix(24)).png"
            let url = Self.imagesDir.appendingPathComponent(name)
            if !FileManager.default.fileExists(atPath: url.path) { try? png.write(to: url) }
            return ClipEntry(kind: .image, imageFile: name, imageSize: CGSize(width: rep.pixelsWide, height: rep.pixelsHigh),
                             date: Date(), hash: h)
        }
        return nil
    }

    private func insert(_ e: ClipEntry) {
        var e = e
        if let i = entries.firstIndex(where: { $0.hash == e.hash }) {
            // Same content again: move it to the top, keep its pin and use count.
            let old = entries.remove(at: i)
            e.id = old.id
            e.pinned = old.pinned
            e.useCount = old.useCount
            if e.app == nil { e.app = old.app }
        }
        entries.insert(e, at: 0)
        prune()
        scheduleSave()
    }

    private func prune() {
        let cutoff = settings.clipboardDays > 0 ? Date().addingTimeInterval(-Double(settings.clipboardDays) * 86_400) : nil
        var kept: [ClipEntry] = []
        var unpinned = 0
        for e in entries {
            if e.pinned { kept.append(e); continue }
            if let cutoff, e.date < cutoff { continue }
            unpinned += 1
            if unpinned > settings.clipboardLimit { continue }
            kept.append(e)
        }
        if kept.count != entries.count {
            entries = kept
            cleanImages()
        }
    }

    private func cleanImages() {
        let used = Set(entries.compactMap(\.imageFile))
        let files = (try? FileManager.default.contentsOfDirectory(atPath: Self.imagesDir.path)) ?? []
        for f in files where !used.contains(f) {
            try? FileManager.default.removeItem(at: Self.imagesDir.appendingPathComponent(f))
        }
    }

    private func scheduleSave() {
        saveWork?.cancel()
        let work = DispatchWorkItem { [weak self] in
            guard let self else { return }
            JSONFile.save(self.entries, to: Self.file)
        }
        saveWork = work
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.8, execute: work)
    }

    // MARK: - Editing

    func togglePin(_ id: UUID) {
        guard let i = entries.firstIndex(where: { $0.id == id }) else { return }
        entries[i].pinned.toggle()
        scheduleSave()
    }

    func delete(_ id: UUID) {
        entries.removeAll { $0.id == id }
        cleanImages()
        scheduleSave()
    }

    func clear(keepPinned: Bool = true) {
        entries.removeAll { !keepPinned || !$0.pinned }
        cleanImages()
        scheduleSave()
    }

    func markUsed(_ id: UUID) {
        guard let i = entries.firstIndex(where: { $0.id == id }) else { return }
        entries[i].useCount += 1
        scheduleSave()
    }

    func image(for e: ClipEntry) -> NSImage? {
        guard let f = e.imageFile else { return nil }
        return ThumbnailCache.image(Self.imagesDir.appendingPathComponent(f))
    }

    /// Writes an entry back to the pasteboard in its original form.
    func write(_ e: ClipEntry, plain: Bool = false, to pb: NSPasteboard) {
        noteOwnWrite()
        switch e.kind {
        case .text, .link, .color:
            pb.setString(e.text ?? "", forType: .string)
            if e.kind == .link, !plain, let u = e.text.flatMap(URL.init(string:)) {
                pb.setString(u.absoluteString, forType: .URL)
            }
        case .image:
            if let f = e.imageFile, let data = try? Data(contentsOf: Self.imagesDir.appendingPathComponent(f)) {
                pb.setData(data, forType: .png)
                if let img = NSImage(data: data), let tiff = img.tiffRepresentation { pb.setData(tiff, forType: .tiff) }
            }
        case .files:
            let urls = (e.files ?? []).map { URL(fileURLWithPath: $0) as NSURL }
            if plain { pb.setString((e.files ?? []).joined(separator: "\n"), forType: .string) } else { pb.writeObjects(urls) }
        }
    }

    private static func hash(_ s: String) -> String { hash(Data(s.utf8)) }
    private static func hash(_ d: Data) -> String {
        SHA256.hash(data: d).map { String(format: "%02x", $0) }.joined()
    }
}

/// Decoded thumbnails for list rows and previews.
@MainActor
enum ThumbnailCache {
    private static var cache: [URL: NSImage] = [:]
    static func image(_ url: URL) -> NSImage? {
        if let hit = cache[url] { return hit }
        guard let img = NSImage(contentsOf: url) else { return nil }
        if cache.count > 120 { cache.removeAll() }
        cache[url] = img
        return img
    }
}

/// "#FF8800", "#f80", "rgb(255, 136, 0)", "rgba(…)", "hsl(…)".
enum ColorParser {
    static func parse(_ s: String) -> NSColor? {
        let t = s.trimmingCharacters(in: .whitespaces).lowercased()
        if t.hasPrefix("#") {
            let hex = String(t.dropFirst())
            guard [3, 4, 6, 8].contains(hex.count), hex.allSatisfy(\.isHexDigit), let v = UInt64(hex, radix: 16) else { return nil }
            func c(_ shift: UInt64, _ bits: UInt64) -> CGFloat { CGFloat((v >> shift) & ((1 << bits) - 1)) / CGFloat((1 << bits) - 1) }
            switch hex.count {
            case 3: return NSColor(srgbRed: c(8, 4), green: c(4, 4), blue: c(0, 4), alpha: 1)
            case 4: return NSColor(srgbRed: c(12, 4), green: c(8, 4), blue: c(4, 4), alpha: c(0, 4))
            case 6: return NSColor(srgbRed: c(16, 8), green: c(8, 8), blue: c(0, 8), alpha: 1)
            default: return NSColor(srgbRed: c(24, 8), green: c(16, 8), blue: c(8, 8), alpha: c(0, 8))
            }
        }
        if let m = t.firstMatch(#"^rgba?\(\s*(\d{1,3})\s*,\s*(\d{1,3})\s*,\s*(\d{1,3})\s*(?:,\s*([\d.]+)\s*)?\)$"#),
           let r = Double(m[1]), let g = Double(m[2]), let b = Double(m[3]), r <= 255, g <= 255, b <= 255 {
            return NSColor(srgbRed: r / 255, green: g / 255, blue: b / 255, alpha: Double(m[4]) ?? 1)
        }
        if let m = t.firstMatch(#"^hsla?\(\s*(\d{1,3})\s*,\s*(\d{1,3})%\s*,\s*(\d{1,3})%\s*(?:,\s*([\d.]+)\s*)?\)$"#),
           let h = Double(m[1]), let sat = Double(m[2]), let l = Double(m[3]) {
            // HSL → HSB
            let L = l / 100, S = sat / 100
            let v = L + S * min(L, 1 - L)
            let sb = v == 0 ? 0 : 2 * (1 - L / v)
            return NSColor(hue: h / 360, saturation: sb, brightness: v, alpha: Double(m[4]) ?? 1)
        }
        return nil
    }

    static func hex(_ c: NSColor) -> String {
        guard let s = c.usingColorSpace(.sRGB) else { return "#000000" }
        return String(format: "#%02X%02X%02X", Int(round(s.redComponent * 255)), Int(round(s.greenComponent * 255)), Int(round(s.blueComponent * 255)))
    }

    static func rgb(_ c: NSColor) -> String {
        guard let s = c.usingColorSpace(.sRGB) else { return "rgb(0, 0, 0)" }
        return "rgb(\(Int(round(s.redComponent * 255))), \(Int(round(s.greenComponent * 255))), \(Int(round(s.blueComponent * 255))))"
    }

    static func hsl(_ c: NSColor) -> String {
        guard let s = c.usingColorSpace(.sRGB) else { return "hsl(0, 0%, 0%)" }
        let r = s.redComponent, g = s.greenComponent, b = s.blueComponent
        let mx = max(r, g, b), mn = min(r, g, b)
        let l = (mx + mn) / 2
        var h: CGFloat = 0, sat: CGFloat = 0
        if mx != mn {
            let d = mx - mn
            sat = l > 0.5 ? d / (2 - mx - mn) : d / (mx + mn)
            switch mx {
            case r: h = (g - b) / d + (g < b ? 6 : 0)
            case g: h = (b - r) / d + 2
            default: h = (r - g) / d + 4
            }
            h /= 6
        }
        return "hsl(\(Int(round(h * 360))), \(Int(round(sat * 100)))%, \(Int(round(l * 100)))%)"
    }
}
